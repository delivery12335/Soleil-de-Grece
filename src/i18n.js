const visualClassByNote = Object.fromEntries(
  Object.entries(noteVisuals).flatMap(([key, notes]) => notes.map((note) => [note, key])),
);

export const t = (key) => ui[currentLanguage.value][key] || ui.ru[key] || key;

export const translate = (value) => {
  if (value && typeof value === 'object') {
    return value[currentLanguage.value] || value.ru || value.en || '';
  }
  if (currentLanguage.value === 'ru') return value;
  return translations[value] || value;
};

export const perfumeDescription = (perfume) => (
  currentLanguage.value === 'en' ? perfumeCopy[perfume.slug]?.description || perfume.description : perfume.description
);

export const perfumeDetails = (perfume) => {
  if (perfume.details && typeof perfume.details === 'object') {
    return perfume.details[currentLanguage.value] || perfume.details.ru || perfume.details.en || '';
  }

  return currentLanguage.value === 'en'
    ? perfumeCopy[perfume.slug]?.details || perfume.details
    : perfume.details;
};

export const noteLabel = (note) => translate(note);

export const noteImage = (note) => {
  const translated = translations[note] || note;
  const slug = noteImages[translated] || 'default';
  return assetUrl(`images/notes/${slug}.jpg`);
};

export const noteVisualClass = (note) => visualClassByNote[note] || 'default';

export const noteIcon = (note) => noteIcons[noteVisualClass(note)] || noteIcons.default;
